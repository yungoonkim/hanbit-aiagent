# ============================================================================
# [6.5절] RAG 에이전트의 공유 상태 정의 (rag_agent/state.py)
# ============================================================================
# 이 파일은 문서를 검색해서 답변하고 스스로 검증까지 하는 Self-RAG / Corrective RAG 에이전트가
# 각 단계(노드)마다 돌려보는 '공유 업무 일지(AgentState)'를 정의합니다.
#
# 💡 비전공자를 위한 일상 비유:
# - 기본 `MessagesState`가 단순한 "대화 기록장"이라면,
# - `AgentState`는 그 대화 기록장에 더해 **현재 찾는 질문(question)**, **도서관에서 찾은 자료(context)**,
#   **작성한 답변 초안(answer)**, **재검색 시도 횟수(retry_num)** 칸을 추가로 만든 '연구 노트'입니다!
# ============================================================================

from langgraph.graph import MessagesState

class AgentState(MessagesState):
    question: str   # 사용자의 원래 질문 (또는 검색이 잘 되도록 다듬어진 질문)
    context: str    # 벡터 데이터베이스(PDF)에서 찾아낸 참고 문서 내용
    answer: str     # 참고 문서를 바탕으로 AI가 작성한 최종 답변
    retry_num: int  # 원하는 자료가 안 나와서 질문을 바꿔 다시 검색한 횟수 (무한 루프 방지용!)
